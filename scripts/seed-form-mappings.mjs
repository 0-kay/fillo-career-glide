// Generates a SQL migration that seeds public.form_mappings from the inline MATCH_CONFIG in the
// match-config edge function, so cached behaviour starts identical to what production serves today.
//   node scripts/seed-form-mappings.mjs
// Only flat `fields` are seeded. `arrays` and `screeningQuestions` keep being served by
// match-config and handled by the extension engine.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

export function readMatchConfig() {
  const src = readFileSync(resolve(here, "../supabase/functions/match-config/index.ts"), "utf8");
  const start = src.indexOf("const MATCH_CONFIG = ") + "const MATCH_CONFIG = ".length;
  const end = src.indexOf(";\n\nserve(", start);
  if (start < 30 || end < 0) throw new Error("Could not locate MATCH_CONFIG in match-config/index.ts");
  return JSON.parse(src.slice(start, end));
}

// Must stay in sync with supabase/functions/_shared/formfill/signature.ts.
const normalizeText = (s) => String(s ?? "").toLowerCase().replace(/[*:]/g, " ").replace(/[^a-z0-9]+/g, " ").trim();
const UNSTABLE = /^(input|field|react-?select|mui|radix|:r)?[-_:]?\d+$|[0-9a-f]{8,}|\d{4,}/i;
const stableToken = (raw) => {
  const s = String(raw ?? "").trim().replace(/^-?\d+[_-]/, "");
  return !s || UNSTABLE.test(s) ? "" : s.toLowerCase();
};

/** Seed rows in form_mappings column shape (no id). */
export function rowsFromConfig(config) {
  const rows = [];
  const seen = new Set();
  for (const [pattern, cfg] of Object.entries(config.domains)) {
    for (const f of cfg.fields ?? []) {
      if (!f.profilePath) continue;
      const type = normalizeText(f.type) || "text";
      const name = stableToken(f.name);
      const label = normalizeText(f.label);
      const signature = `${type}|${name}|${label}`;
      const dedupe = `${pattern}|${signature}`;
      if (seen.has(dedupe)) continue;
      seen.add(dedupe);
      const meta = {};
      if (f.default) meta.default = f.default;
      if (f.options) meta.options = f.options;
      rows.push({
        scope: "platform",
        domain_pattern: pattern,
        platform: cfg.platform,
        signature,
        field_name: name,
        field_label: label,
        field_type: type,
        profile_path: f.profilePath,
        selector: f.selector ?? null,
        meta,
        source: "seed",
        confidence: 100,
      });
    }
  }
  return rows;
}

const q = (v) => (v == null ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rows = rowsFromConfig(readMatchConfig()).map(
    (r) =>
      `  ('platform', ${q(r.domain_pattern)}, ${q(r.platform)}, ${q(r.signature)}, ${q(r.field_name)}, ${q(r.field_label)}, ${q(r.field_type)}, ${q(r.profile_path)}, ${q(r.selector)}, ${q(JSON.stringify(r.meta))}::jsonb, 'seed', 100)`,
  );
  const sql = `-- Generated by scripts/seed-form-mappings.mjs from the match-config edge function. Do not edit by hand.
INSERT INTO public.form_mappings
  (scope, domain_pattern, platform, signature, field_name, field_label, field_type, profile_path, selector, meta, source, confidence)
VALUES
${rows.join(",\n")}
ON CONFLICT (scope, domain_pattern, kind, signature) DO NOTHING;
`;
  const out = resolve(here, "../supabase/migrations/20260926000100-seed-form-mappings.sql");
  writeFileSync(out, sql);
  console.log(`wrote ${rows.length} rows -> ${out}`);
}
